"""The table shape, defined exactly once.

``COLUMNS`` is the single source of column order for every backend's INSERT and
for the DDL emitted by :func:`ddl_for`. The DDL is hand-written to match what
Django's own migration produces for
``eventlog_pro.contrib.django.models.EventLog``, so a table created by the core
backends can be adopted by ``migrate --fake-initial`` and both modes can read
each other's rows. ``tests/test_schema_parity.py`` enforces that promise.
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Any, Final

from .exceptions import BackendError, ConfigurationError

if TYPE_CHECKING:  # pragma: no cover
    from .criteria import Criteria

